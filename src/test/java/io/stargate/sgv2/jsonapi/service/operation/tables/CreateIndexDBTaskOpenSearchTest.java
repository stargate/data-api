package io.stargate.sgv2.jsonapi.service.operation.tables;

import static org.assertj.core.api.Assertions.assertThat;

import io.stargate.sgv2.jsonapi.api.model.command.table.definition.indexes.OpenSearchIndexDefinitionDesc;
import io.stargate.sgv2.jsonapi.fixtures.testdata.TestData;
import io.stargate.sgv2.jsonapi.service.cqldriver.executor.DefaultDriverExceptionHandler;
import io.stargate.sgv2.jsonapi.service.operation.SchemaDBTask;
import io.stargate.sgv2.jsonapi.service.schema.tables.ApiOpenSearchIndex;
import io.stargate.sgv2.jsonapi.service.schema.tables.TableSchemaObject;
import java.time.Duration;
import java.util.List;
import org.junit.jupiter.api.Test;

/** Tests the CQL generated by {@link CreateIndexDBTask} for an OpenSearch index. */
public class CreateIndexDBTaskOpenSearchTest {

  private static final TestData TEST_DATA = new TestData();
  private static final TableSchemaObject TABLE = TEST_DATA.schemaObject().tableWithMapSetList();

  private static String cqlFor(OpenSearchIndexDefinitionDesc definition) {
    var apiIndex = ApiOpenSearchIndex.FROM_DESC_FACTORY.create(TABLE, "my_os_idx", definition);
    var task =
        CreateIndexDBTask.builder(TABLE)
            .withIfNotExists(false)
            .withSchemaRetryPolicy(new SchemaDBTask.SchemaRetryPolicy(1, Duration.ofMillis(1)))
            .withExceptionHandlerFactory(
                DefaultDriverExceptionHandler.Factory.withIdentifier(
                    CreateIndexExceptionHandler::new, apiIndex.indexName()))
            .build(apiIndex);
    return task.buildStatement().getQuery();
  }

  @Test
  public void allListedColumnsAreIndexed() {
    var names = TEST_DATA.names;
    var cql =
        cqlFor(
            new OpenSearchIndexDefinitionDesc(
                List.of(
                    names.CQL_TEXT_COLUMN.asInternal(),
                    names.CQL_ASCII_COLUMN.asInternal(),
                    names.CQL_INT_COLUMN.asInternal()),
                null));

    assertThat(cql)
        .contains(
            " ("
                + names.CQL_TEXT_COLUMN.asInternal()
                + ","
                + names.CQL_ASCII_COLUMN.asInternal()
                + ","
                + names.CQL_INT_COLUMN.asInternal()
                + ") ")
        .contains("USING 'OpenSearchIndex'");
  }

  @Test
  public void singleColumn() {
    var col = TEST_DATA.names.CQL_TEXT_COLUMN.asInternal();
    var cql = cqlFor(new OpenSearchIndexDefinitionDesc(List.of(col), null));

    assertThat(cql).contains(" (" + col + ") USING 'OpenSearchIndex'");
  }

  @Test
  public void noColumnsGivesEmptyColumnList() {
    var cql = cqlFor(new OpenSearchIndexDefinitionDesc(null, null));

    assertThat(cql).contains(" () USING 'OpenSearchIndex'");
  }
}
